import 'dart:async';
import 'dart:convert';
import 'dart:io';
import 'package:http/http.dart' as http;
import 'ai_product.dart';

// ============================================================================
// 1. ฟังก์ชันดึงข้อมูลสินค้าทั้งหมด (List<AiProduct>)
// ============================================================================
/// ฟังก์ชันดึงข้อมูลสินค้าทั้งหมดจาก FakeStore API
/// - URL: GET https://fakestoreapi.com/products
/// - Timeout: ไม่เกิน 10 วินาที
/// - Return: Future<List<AiProduct>>
Future<List<AiProduct>> fetchAiProducts() async {
  const String url = 'https://fakestoreapi.com/products';

  try {
    // กำหนด Timeout ไม่เกิน 10 วินาที เพื่อไม่ให้ผู้ใช้รอนานเกินไปหากเครือข่ายมีปัญหา
    final response = await http
        .get(Uri.parse(url))
        .timeout(const Duration(seconds: 10));

    // ตรวจสอบ HTTP Status Code
    if (response.statusCode == 200) {
      final dynamic decodedData = jsonDecode(response.body);

      // ตรวจสอบว่าผลลัพธ์เป็น List หรือไม่ เพื่อป้องกันข้อผิดพลาดเวลาแปลงข้อมูล
      if (decodedData is! List) {
        throw const FormatException('ข้อมูลที่ได้รับไม่อยู่ในรูปแบบรายการสินค้า (List)');
      }

      return decodedData
          .map<AiProduct>((item) => AiProduct.fromJson(item as Map<String, dynamic>))
          .toList();
    } else {
      // เซิร์ฟเวอร์ตอบกลับรหัสสถานะอื่น เช่น 404 Not Found หรือ 500 Server Error
      throw Exception('เซิร์ฟเวอร์ตอบสนองผิดพลาด (รหัสสถานะ: ${response.statusCode})');
    }
  } on TimeoutException {
    // ------------------------------------------------------------------------
    // ทำไมต้องดักจับ TimeoutException:
    // เกิดขึ้นเมื่อคำขอ (Request) ใช้เวลานานเกินกว่าระยะเวลาที่กำหนดใน .timeout(Duration(seconds: 10))
    // เช่น เน็ตช้ามาก คลื่นโทรศัพท์อ่อน หรือเซิร์ฟเวอร์ปลายทางค้างไม่ยอมตอบกลับ
    // การดักจับจุดนี้ช่วยป้องกันไม่ให้ Future ค้างเติ่ง และสามารถแจ้งให้ผู้ใช้ทราบว่าคำขอหมดเวลา
    // ------------------------------------------------------------------------
    throw Exception('การเชื่อมต่อหมดเวลา กรุณาลองใหม่อีกครั้งในภายหลัง');
  } on http.ClientException {
    // ------------------------------------------------------------------------
    // ทำไมต้องดักจับ http.ClientException:
    // เป็น Exception เฉพาะของแพ็กเกจ http เมื่อ Client ไม่สามารถส่งคำขอไปยัง Host ได้
    // สาเหตุหลักคือ เครื่องไม่มีการเชื่อมต่ออินเทอร์เน็ต, เปิด Airplane mode, หรือ DNS Lookup ล้มเหลว (ไม่พบ Domain)
    // การดักจับจุดนี้ช่วยแปลง error เชิงเทคนิคเป็นภาษาไทย เพื่อให้ผู้ใช้ตรวจเช็คการเชื่อมต่อเน็ตของตนเอง
    // ------------------------------------------------------------------------
    throw Exception('ไม่สามารถเชื่อมต่ออินเทอร์เน็ตได้ กรุณาตรวจสอบสัญญาณเน็ตของคุณ');
  } on SocketException {
    // ------------------------------------------------------------------------
    // ทำไมต้องดักจับ SocketException:
    // เป็น Exception ระดับ OS Network Socket (dart:io) บนระบบปฏิบัติการ Android/iOS
    // ในบางสถานการณ์ เช่น ปิดเน็ตกะทันหัน หรือหลุดจาก Wi-Fi การเรียกระดับต่ำจะโยน SocketException
    // ออกมาก่อนที่จะถูกห่อหุ้มเป็น ClientException จึงจำเป็นต้องดักจับคู่กันเพื่อความรัดกุม 100%
    // ------------------------------------------------------------------------
    throw Exception('ไม่สามารถเชื่อมต่ออินเทอร์เน็ตได้ กรุณาตรวจสอบสัญญาณเน็ตของคุณ');
  } on FormatException {
    // ------------------------------------------------------------------------
    // ทำไมต้องดักจับ FormatException:
    // เกิดขึ้นเมื่อ jsonDecode(...) ล้มเหลว เนื่องจาก String ใน response.body ไม่ได้เป็นโครงสร้าง JSON ที่ถูกต้อง
    // เช่น เซิร์ฟเวอร์ส่งหน้า HTML Error Page (เช่น 502 Bad Gateway ของ Cloudflare) หรือข้อมูลขาดหายระหว่างส่ง
    // รวมถึงกรณีที่เรา throw เองเมื่อรูปแบบข้อมูลไม่เป็น List ตามที่คาดหวัง
    // การดักจับจุดนี้ช่วยป้องกันไม่ให้แอป Crash จากการพยายาม parse ข้อความผิดรูปแบบ
    // ------------------------------------------------------------------------
    throw Exception('ข้อมูลสินค้าจากเซิร์ฟเวอร์ไม่ถูกต้องหรือไม่สามารถประมวลผลได้');
  } catch (e) {
    // ------------------------------------------------------------------------
    // ทำไมต้องมี catch (e) ทั่วไป:
    // เป็น Fallback ปลอดภัยขั้นสุดท้ายสำหรับดักจับข้อยกเว้นที่เราโยนเอง (custom exception)
    // หรือข้อผิดพลาดที่ไม่คาดคิดอื่นๆ (Unforeseen Errors) เพื่อให้แอปไม่หลุดออกจากหน้าจอ
    // ------------------------------------------------------------------------
    final errorStr = e.toString();
    if (errorStr.startsWith('Exception: ')) {
      throw Exception(errorStr.replaceFirst('Exception: ', ''));
    }
    throw Exception('เกิดข้อผิดพลาดที่ไม่คาดคิด กรุณาลองใหม่อีกครั้ง');
  }
}

// ============================================================================
// 2. ฟังก์ชันดึงข้อมูลสินค้ารายการเดียวตาม ID (Future<AiProduct>)
// ============================================================================
/// ฟังก์ชันดึงข้อมูลสินค้ารายการเดียวตาม id จาก FakeStore API
/// - URL: GET https://fakestoreapi.com/products/{id}
/// - Timeout: ไม่เกิน 10 วินาที
/// - Return: Future<AiProduct>
Future<AiProduct> fetchAiProductById(int id) async {
  // ตรวจสอบเบื้องต้นว่า id ต้องมีค่ามากกว่า 0
  if (id <= 0) {
    throw Exception('รหัสสินค้าไม่ถูกต้อง (id ต้องมากกว่า 0)');
  }

  final String url = 'https://fakestoreapi.com/products/$id';

  try {
    // กำหนด Timeout 10 วินาทีเช่นเดียวกับฟังก์ชันหลัก
    final response = await http
        .get(Uri.parse(url))
        .timeout(const Duration(seconds: 10));

    if (response.statusCode == 200) {
      // ตรวจสอบกรณี API ตอบกลับเป็น body ว่างเปล่า หรือคำว่า "null"
      if (response.body.trim().isEmpty || response.body.trim() == 'null') {
        throw Exception('ไม่พบข้อมูลสินค้ารหัส $id ในระบบ');
      }

      final dynamic decodedData = jsonDecode(response.body);

      // ตรวจสอบว่าผลลัพธ์เป็น Map<String, dynamic> หรือไม่ (เนื่องจากต้องการรายการเดียว ไม่ใช่ List)
      if (decodedData is! Map<String, dynamic>) {
        throw const FormatException('ข้อมูลสินค้าที่ได้รับไม่อยู่ในรูปแบบ Object (Map)');
      }

      // แปลงข้อมูลเป็น AiProduct เพียงรายการเดียว
      return AiProduct.fromJson(decodedData);
    } else if (response.statusCode == 404) {
      throw Exception('ไม่พบสินค้ารหัส $id ในระบบ (รหัสสถานะ: 404)');
    } else {
      // รหัสสถานะอื่นๆ เช่น 500, 503
      throw Exception('เซิร์ฟเวอร์ตอบสนองผิดพลาด (รหัสสถานะ: ${response.statusCode})');
    }
  } on TimeoutException {
    // ------------------------------------------------------------------------
    // ทำไมต้องดักจับ TimeoutException:
    // ป้องกันการค้างหมุนไม่รู้จบเมื่อการเชื่อมต่อช้า หรือเซิร์ฟเวอร์ไม่ตอบกลับภายใน 10 วินาที
    // ------------------------------------------------------------------------
    throw Exception('การเชื่อมต่อหมดเวลา กรุณาลองใหม่อีกครั้งในภายหลัง');
  } on http.ClientException {
    // ------------------------------------------------------------------------
    // ทำไมต้องดักจับ http.ClientException:
    // ดักจับปัญหาไม่มีอินเทอร์เน็ตบนอุปกรณ์ หรือ DNS Lookup ล้มเหลวจากฝั่ง Client
    // ------------------------------------------------------------------------
    throw Exception('ไม่สามารถเชื่อมต่ออินเทอร์เน็ตได้ กรุณาตรวจสอบสัญญาณเน็ตของคุณ');
  } on SocketException {
    // ------------------------------------------------------------------------
    // ทำไมต้องดักจับ SocketException:
    // ดักจับข้อผิดพลาดระดับ OS Socket เมื่อไม่มีการเชื่อมต่อเครือข่ายบนอุปกรณ์มือถือ
    // ------------------------------------------------------------------------
    throw Exception('ไม่สามารถเชื่อมต่ออินเทอร์เน็ตได้ กรุณาตรวจสอบสัญญาณเน็ตของคุณ');
  } on FormatException {
    // ------------------------------------------------------------------------
    // ทำไมต้องดักจับ FormatException:
    // ป้องกันแอป Crash เมื่อข้อมูลที่ส่งกลับมาไม่ใช่ JSON ที่ถูกต้อง หรือไม่ใช่ Map Object
    // ------------------------------------------------------------------------
    throw Exception('ข้อมูลสินค้าจากเซิร์ฟเวอร์ไม่ถูกต้องหรือไม่สามารถประมวลผลได้');
  } catch (e) {
    // ------------------------------------------------------------------------
    // ทำไมต้องมี catch (e) ทั่วไป:
    // ป้องกันแอป Crash จากข้อผิดพลาดที่ไม่ได้คาดคิด และส่งต่อข้อความภาษาไทยที่มีอยู่แล้ว
    // ------------------------------------------------------------------------
    final errorStr = e.toString();
    if (errorStr.startsWith('Exception: ')) {
      throw Exception(errorStr.replaceFirst('Exception: ', ''));
    }
    throw Exception('เกิดข้อผิดพลาดที่ไม่คาดคิด กรุณาลองใหม่อีกครั้ง');
  }
}
